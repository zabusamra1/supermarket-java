package edu.collin.cosc2436.team4.cashregister;

/**
 * The RetailItem enum represents the different retail items
 * that can be sold by the cash register.
 *
 * The implicit toString() method of the enum is used to
 * print the item names on the receipt.
 */
public enum RetailItem {
	CHIPS,
	CEREAL,
	SOAP,
	SODA;
}
